// Equal-quality glyphs at different offsets must stay ambiguous. The fixture
// is a synthetic 34x26 card badge, not a private capture.
const productionTieFixture = `..................................
..................................
..................................
..................................
..............########.#..........
...........###############........
...........################.......
...........###..###########.......
.......................####.......
......................#####.......
...............#...##.#####.......
............###############.......
............##############........
.............############.#.......
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................`

func TestStorageRunnerUpEqualQualityRemainsConflict(t *testing.T) {
	img := image.NewRGBA(image.Rect(0, 0, 34, 26))
	for y, row := range strings.Split(productionTieFixture, "\n") {
		for x, c := range row {
			if c == '#' {
				img.SetRGBA(x, y, color.RGBA{R: 255, G: 255, B: 255, A: 255})
			}
		}
	}
	layout := StorageLayout()
	got := (&PixelMatcher{}).positionVerdict(img, img.Bounds(), layout.CardPositions)
	if !got.Conflict {
		t.Fatalf("verdict = %+v, want conflict for equal-quality offsets", got)
	}
}

// The global runner-up can be weak at the winner's offset while a third set
// is stronger there. Rescore all other sets, not just the global runner-up.
func TestStorageRunnerUpRechecksAllSetsAtWinnerOffset(t *testing.T) {
	base := strings.Repeat("#", 20)
	one := base + "......"
	two := strings.Repeat("#", 19) + "......#"
	three := "." + strings.Repeat("#", 19) + "......"
	shape := func(rows ...string) glyphSet {
		return glyphSet{minBrightness: 180, minScore: .88, minMargin: .04, masks: []glyphMask{{rows: rows}}}
	}
	img := image.NewRGBA(image.Rect(0, 0, 27, 2))
	for i, c := range one + "#" {
		if c == '#' {
			img.SetRGBA(i, 0, color.RGBA{R: 255, G: 255, B: 255, A: 255})
			img.SetRGBA(i, 1, color.RGBA{R: 255, G: 255, B: 255, A: 255})
		}
	}
	templates := [6]glyphSet{shape(one, one), shape(two, "."+two[1:]), shape(three, three)}
	got := (&PixelMatcher{}).positionVerdict(img, img.Bounds(), templates)
	if !got.Conflict {
		t.Fatalf("verdict = %+v, want conflict when the third set is close at winner offset", got)
	}
}
