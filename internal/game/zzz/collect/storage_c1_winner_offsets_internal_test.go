package collect

import (
	"image"
	"image/color"
	"strings"
	"testing"
)

// The winner itself can have two equal-quality placements. Both must hold
// the runner-up margin before the card is admitted; picking the first placement
// would let iteration order decide whether the cell is known or conflicted.
const equalWinnerOffsetsFixture = `..................................
..................................
..................................
.......#.....#.#..................
.........############.............
.......################...........
.......################...........
..................######..........
..................#####...........
..................######..........
.........##############...........
........###############...........
.........###########.#............
...........#....#.................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................
..................................`

func TestStorageRunnerUpChecksAllWinnerOffsets(t *testing.T) {
	img := image.NewRGBA(image.Rect(0, 0, 34, 26))
	for y, row := range strings.Split(equalWinnerOffsetsFixture, "\n") {
		for x, c := range row {
			if c == '#' {
				img.SetRGBA(x, y, color.RGBA{R: 255, G: 255, B: 255, A: 255})
			}
		}
	}
	layout := StorageLayout()
	got := (&PixelMatcher{}).positionVerdict(img, img.Bounds(), layout.CardPositions)
	if !got.Conflict {
		t.Fatalf("verdict = %+v, want conflict when an equal-quality winner offset fails the margin", got)
	}
}
