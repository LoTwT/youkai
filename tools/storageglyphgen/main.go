// Command storageglyphgen turns a BadgeShape model export into the small
// generated Go file used by the production card glyph confirmation. It reads
// only derived numeric weights; it never reads images, ROIs, ledgers or
// private recordings.
package main

import (
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"strings"
)

type export struct {
	Schema           string     `json:"schema"`
	Core             []int      `json:"core"`
	Anchor           string     `json:"anchor"`
	Feature          string     `json:"feature"`
	Ridge            float64    `json:"ridge"`
	MinLDAScore      float64    `json:"min_lda_score"`
	TrainManifestSHA string     `json:"train_manifest_sha256"`
	TrainSamples     int        `json:"train_samples"`
	TrainObjects     int        `json:"train_objects"`
	Weights          []*float64 `json:"w"`
	Bias             *float64   `json:"bias"`
}

func main() {
	var model, out string
	flag.StringVar(&model, "model", "", "BadgeShape model-export.json")
	flag.StringVar(&out, "out", "internal/game/zzz/collect/storage_card_glyph_model.go", "generated Go file")
	flag.Parse()
	if model == "" {
		fail("-model is required")
	}
	raw, err := os.ReadFile(model)
	if err != nil {
		fail(err.Error())
	}
	var e export
	if err := json.Unmarshal(raw, &e); err != nil {
		fail(err.Error())
	}
	if err := validateExport(e); err != nil {
		fail(err.Error())
	}
	if !strings.HasSuffix(out, "storage_card_glyph_model.go") {
		fail("refusing to overwrite a destination other than storage_card_glyph_model.go")
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fail(err.Error())
	}
	formatted, err := renderModel(e)
	if err != nil {
		fail(err.Error())
	}
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		fail(err.Error())
	}
	fmt.Printf("storageglyphgen: wrote %s (weights=%d, objects=%d)\n", out, len(e.Weights), e.TrainObjects)
}

// validateExport is the model contract. It deliberately rejects a missing
// anchor rather than guessing component vs fixed from the coefficients.
func validateExport(e export) error {
	if e.Schema != "badge-lda-export-v1" || len(e.Core) != 4 || e.Core[0] != 6 || e.Core[1] != 5 || e.Core[2] != 21 || e.Core[3] != 16 {
		return fmt.Errorf("unexpected model schema/core")
	}
	if e.Anchor != "component" {
		return fmt.Errorf("anchor must be component; fixed anchor is not the validated contract")
	}
	if len(e.Weights) != cardFeatureLen {
		return fmt.Errorf("weight length %d, want %d", len(e.Weights), cardFeatureLen)
	}
	if e.MinLDAScore <= 0 || math.IsNaN(e.MinLDAScore) || math.IsInf(e.MinLDAScore, 0) {
		return fmt.Errorf("min_lda_score must be finite and positive")
	}
	if len(e.TrainManifestSHA) != 64 {
		return fmt.Errorf("training manifest SHA-256 must be 64 hexadecimal characters")
	}
	if _, err := hex.DecodeString(e.TrainManifestSHA); err != nil {
		return fmt.Errorf("training manifest SHA-256 is not hexadecimal: %w", err)
	}
	if e.Bias == nil {
		return fmt.Errorf("bias is required and must not be null")
	}
	if math.IsNaN(*e.Bias) || math.IsInf(*e.Bias, 0) {
		return fmt.Errorf("bias must be finite")
	}
	for i, w := range e.Weights {
		if w == nil {
			return fmt.Errorf("weight %d is null", i)
		}
		if math.IsNaN(*w) || math.IsInf(*w, 0) {
			return fmt.Errorf("weight %d is not finite", i)
		}
	}
	return nil
}

func renderModel(e export) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/storageglyphgen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Model schema: %s\n", e.Schema)
	fmt.Fprintf(&b, "// Feature (canonical): 336 row-major z-normalized luma values, 16 row means, 21 column means. Source feature description is intentionally ignored.\n")
	fmt.Fprintf(&b, "// Training manifest SHA-256: %s; samples=%d objects=%d; ridge=%.6g; min_score=%.6g\n", e.TrainManifestSHA, e.TrainSamples, e.TrainObjects, e.Ridge, e.MinLDAScore)
	fmt.Fprintf(&b, "package collect\n\n")
	fmt.Fprintf(&b, "var storageCardGlyphLDA = cardGlyphLDA{\n")
	fmt.Fprintf(&b, "\tVersion: %q,\n", e.TrainManifestSHA)
	fmt.Fprintf(&b, "\tMinScore: %.17g,\n", e.MinLDAScore)
	fmt.Fprintf(&b, "\tBias: %.17g,\n", *e.Bias)
	fmt.Fprintf(&b, "\tWeights: []float64{\n")
	for i, w := range e.Weights {
		if i%8 == 0 {
			b.WriteString("\t\t")
		}
		fmt.Fprintf(&b, "%.17g, ", *w)
		if i%8 == 7 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("\n\t},\n}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated Go is not parseable: %w", err)
	}
	return formatted, nil
}

const cardFeatureLen = 21*16 + 16 + 21

func fail(s string) {
	fmt.Fprintln(os.Stderr, "storageglyphgen:", s)
	os.Exit(2)
}
